"""Verify the real nav2_collision_monitor with the Lite3 profile in an isolated loopback domain.

Starts collision_monitor + its lifecycle manager with params generated by
lite3_locomotion.collision_profile (as navigation.launch.py does), a static odom->base_link TF,
and feeds synthetic /lite3_terrain/hazards clouds + /lite3_ops/mux_out commands. No robot.
Exit 0 only if every expectation holds. Also documents Humble's stale-source behaviour.
"""

import os
from pathlib import Path
import secrets
import signal
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lite3_locomotion import collision_profile as CP  # noqa: E402

BOUNDARY = 0.40            # nose distance of the stop polygon front edge under test


def isolated_env():
    env = os.environ.copy()
    profile = ROOT / 'test' / 'loopback_dds.xml'
    for name in ('ROS_DISCOVERY_SERVER', 'ROS_SUPER_CLIENT', 'FASTDDS_BUILTIN_TRANSPORTS'):
        env.pop(name, None)
    env.update({'ROS_DOMAIN_ID': str(40 + secrets.randbelow(50)), 'ROS_LOCALHOST_ONLY': '1',
                'RMW_IMPLEMENTATION': 'rmw_fastrtps_cpp',
                'FASTRTPS_DEFAULT_PROFILES_FILE': str(profile),
                'FASTDDS_DEFAULT_PROFILES_FILE': str(profile), 'LITE3_CM_CHECK': '1'})
    return env


def scenario():
    import threading
    import numpy as np
    import rclpy
    from rclpy.executors import SingleThreadedExecutor
    from rclpy.node import Node
    from geometry_msgs.msg import Twist, Vector3
    from sensor_msgs.msg import PointCloud2, PointField

    rclpy.init()
    node = Node('lite3_cm_check')
    cmd = node.create_publisher(Twist, '/lite3_ops/mux_out', 10)
    cloud = node.create_publisher(PointCloud2, '/lite3_terrain/hazards', 5)
    out = []
    node.create_subscription(Twist, '/cm_out', lambda m: out.append((time.monotonic(), m.linear.x)), 100)
    executor = SingleThreadedExecutor()
    executor.add_node(node)
    threading.Thread(target=executor.spin, daemon=True).start()

    def make_cloud(points):
        msg = PointCloud2()
        msg.header.stamp = node.get_clock().now().to_msg()
        msg.header.frame_id = 'base_link'
        pts = np.array(points, dtype='<f4').reshape(-1, 3)
        msg.height, msg.width = 1, len(pts)
        msg.fields = [PointField(name=n, offset=4 * i, datatype=7, count=1) for i, n in enumerate('xyz')]
        msg.point_step, msg.row_step, msg.is_dense = 12, 12 * len(pts), True
        msg.data = pts.tobytes()
        return msg

    def phase(seconds, vx, points, publish_cloud=True):
        start = time.monotonic()
        while time.monotonic() - start < seconds:
            if publish_cloud:
                cloud.publish(make_cloud(points))
            cmd.publish(Twist(linear=Vector3(x=vx)))
            time.sleep(0.05)
        return sorted({round(x, 3) for t, x in out if start + seconds * 0.5 <= t < start + seconds})

    def box(nose_distance, y=0.0):
        x = CP.NOSE_M + nose_distance
        return [(x, y + d, 0.1) for d in (-0.05, 0.0, 0.05)] + [(x + 0.05, y, 0.1)]

    phase(6.0, 0.0, [])                                   # discovery + lifecycle activation
    r = {
        'clear, forward 0.051': (phase(2.0, 0.051, []), [0.051]),
        f'object {BOUNDARY - 0.05:.2f} m from nose (inside), forward 0.052': (
            phase(2.0, 0.052, box(BOUNDARY - 0.05)), [0.0]),
        f'object {BOUNDARY + 0.10:.2f} m (outside), forward 0.053': (
            phase(2.0, 0.053, box(BOUNDARY + 0.10)), [0.053]),
        'object inside, zero command': (phase(2.0, 0.0, box(BOUNDARY - 0.05)), [0.0]),
        'object beside the body (y 0.25), forward 0.054': (
            phase(2.0, 0.054, [(0.0, 0.25, 0.1), (0.05, 0.25, 0.1)]), [0.0]),
        'object behind beyond rear (x -0.6), forward 0.055': (
            phase(2.0, 0.055, [(-0.6, 0.0, 0.1), (-0.65, 0.0, 0.1)]), [0.055]),
        'drop cell (z -0.33) inside, forward 0.056': (
            phase(2.0, 0.056, [(CP.NOSE_M + 0.2, 0.0, -0.33), (CP.NOSE_M + 0.25, 0.0, -0.33)]), [0.0]),
    }
    approach = approach_scenario(cmd, cloud, make_cloud, box, out)
    idle_zeros = idle_scenario(cmd, out)
    phase(1.0, 0.057, box(BOUNDARY - 0.05))               # obstacle present ...
    stale = phase(3.0, 0.057, [], publish_cloud=False)    # ... then the source goes silent
    ok = True
    for name, (got, want) in r.items():
        good = got == want
        ok &= good
        print(f'{"PASS" if good else "FAIL"}  {name:<52} output {got} (expected {want})')
    good = idle_zeros > 30
    ok &= good
    print(f'{"PASS" if good else "FAIL"}  zeros still delivered after 12 s of idle ({idle_zeros} of ~40 in 2 s; '
          'Humble goes silent after stop_pub_timeout, we set it to a day)')
    good = approach['ok']
    ok &= good
    print(f'{"PASS" if good else "FAIL"}  M4 approach at {APPROACH_SPEED} m/s: {approach["text"]}')
    print(f'INFO  source silent > source_timeout with last data showing an obstacle: output {stale}'
          f' -> Humble {"IGNORES stale data (robot not stopped by collision_monitor)" if 0.057 in stale else "stops"};'
          ' the terrain_stop lock (0.5 s timeout) is what fails safe on stale perception')
    print('RESULT:', 'PASS' if ok else 'FAIL')
    executor.shutdown()
    node.destroy_node()
    rclpy.shutdown()
    return 0 if ok else 1


APPROACH_SPEED = 0.05      # M4 default walking speed
MAX_RESPONSE_S = 0.10      # one 20 Hz command cycle + DDS on loopback


def approach_scenario(cmd, cloud, make_cloud, box, out):
    """M4 as the collision_monitor sees it: forward commands at 20 Hz, a hazard cloud at 10 Hz
    whose obstacle comes closer at the walking speed. The stop must start with the first cloud
    that puts the obstacle inside the polygon (not earlier), within one command cycle."""
    from geometry_msgs.msg import Twist, Vector3
    start_d = BOUNDARY + 0.30
    t0 = time.monotonic()
    clouds = []          # (publish time, nose distance)
    next_cloud = t0
    while True:
        now = time.monotonic()
        d = start_d - APPROACH_SPEED * (now - t0)
        if d < BOUNDARY - 0.08:
            break
        if now >= next_cloud:
            cloud.publish(make_cloud(box(d)))
            clouds.append((now, d))
            next_cloud += 0.1
        cmd.publish(Twist(linear=Vector3(x=APPROACH_SPEED)))
        time.sleep(0.05)
    t_cross = next((t for t, d in clouds if d <= BOUNDARY + 1e-9), None)
    before = [(t, x) for t, x in out if t0 + 0.5 <= t < (t_cross or now)]
    after = [(t, x) for t, x in out if t_cross is not None and t >= t_cross]
    premature = [t for t, x in before if x == 0.0]
    first_zero = next((t for t, x in after if x == 0.0), None)
    late = [t for t, x in after if x != 0.0 and t > (first_zero or 0.0)]
    response = None if first_zero is None else first_zero - t_cross
    ok = (t_cross is not None and not premature and response is not None and
          response <= MAX_RESPONSE_S and not late and any(x == APPROACH_SPEED for _, x in before))
    text = (f'forward passed until the obstacle reached {BOUNDARY} m; first zero {_fmt(response)} s after '
            f'that cloud (limit {MAX_RESPONSE_S} s); premature zeros {len(premature)}; forward after the '
            f'stop {len(late)}')
    return {'ok': ok, 'text': text, 'response_s': response}


def idle_scenario(cmd, out):
    """Commanded zeros must still reach the robot after the robot has been stopped for > 10 s (the
    default Humble stop_pub_timeout silently ended them; found 2026-11-17 when M10's zero check failed)."""
    from geometry_msgs.msg import Twist
    time.sleep(12.0)
    start, before = time.monotonic(), len(out)
    while time.monotonic() - start < 2.0:
        cmd.publish(Twist())
        time.sleep(0.05)
    return len(out) - before


def _fmt(value):
    return 'none' if value is None else f'{value:.3f}'


def main():
    if os.environ.get('LITE3_CM_CHECK') == '1':
        return scenario()
    import yaml
    env = isolated_env()
    params = CP.collision_monitor_params(BOUNDARY, '/lite3_ops/mux_out', '/cm_out')
    handle, path = tempfile.mkstemp(suffix='.yaml')
    with os.fdopen(handle, 'w') as stream:
        yaml.safe_dump(params, stream)
    print(f'Isolated domain {env["ROS_DOMAIN_ID"]}; stop polygon {CP.stop_polygon(BOUNDARY)}', flush=True)
    procs = [subprocess.Popen(cmd, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                              start_new_session=True) for cmd in (
        ['ros2', 'run', 'tf2_ros', 'static_transform_publisher', '--frame-id', 'odom',
         '--child-frame-id', 'base_link'],
        ['ros2', 'run', 'nav2_collision_monitor', 'collision_monitor', '--ros-args',
         '--params-file', path],
        ['ros2', 'run', 'nav2_lifecycle_manager', 'lifecycle_manager', '--ros-args',
         '-r', '__node:=lifecycle_manager_cm', '-p', 'autostart:=true',
         '-p', 'node_names:=[collision_monitor]'])]
    try:
        return subprocess.call([sys.executable, __file__], env=env, timeout=120)
    finally:
        for p in procs:
            try:
                os.killpg(p.pid, signal.SIGINT)
                p.wait(timeout=5)
            except (subprocess.TimeoutExpired, ProcessLookupError):
                os.killpg(p.pid, signal.SIGKILL)
        os.unlink(path)


if __name__ == '__main__':
    sys.exit(main())
